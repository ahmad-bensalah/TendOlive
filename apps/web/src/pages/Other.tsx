export function Proposals() {
  const list = allTenders().filter(t => analysisFor(t.id) && !['nobid', 'filtered'].includes(t.status))
  // The decks of the proposal studio, by studio id; none when the studio does not answer (the page works without it).
  const [decks, setDecks] = useState<Map<string, Generation>>(() => new Map())
  useEffect(() => { studioDecks().then(setDecks) }, [])
  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div><h1 className="text-[28px] font-semibold tracking-tight">Proposals</h1><p className="mt-1 text-sm text-ink-muted">Drafts built from matching results. Decks are generated by the proposal studio.</p></div>
        <Link to="/templates" className="btn-secondary"><LayoutTemplate size={16} />Deck templates</Link>
      </div>
      {list.length === 0 ? <Card><Empty icon={Presentation} title="No proposal yet" /></Card> : (
        <div className="grid gap-5 md:grid-cols-2 xl:grid-cols-3">
          {list.map(t => {
            const a = analysisFor(t.id)!, p = draftProposal(t, a)
            const deck = decks.get(studioId(t.id)), deckUrl = deck?.status === 'done' ? deckPath(deck, t.id) : null
            return (
              <Card key={t.id} className="flex flex-col p-5">
                <div className="flex items-start gap-3"><ScoreRing value={a.fit_score.overall} size={48} /><div className="min-w-0"><div className="line-clamp-2 font-semibold leading-snug">{t.title}</div><div className="mt-0.5 truncate text-[12px] text-ink-muted">{t.client}</div></div></div>
                <div className="mt-4 grid grid-cols-3 gap-2 text-center text-[12px]">
                  <div className="rounded-ctl bg-canvas py-2"><b className="block text-[16px]">{p.win_themes.length}</b>themes</div>
                  <div className="rounded-ctl bg-canvas py-2"><b className="block text-[16px]">{p.recommended_team.length}</b>people</div>
                  <div className="rounded-ctl bg-canvas py-2"><b className="block text-[16px]">{p.risks.length}</b>risks</div>
                </div>
                <div className="mt-4 flex items-center gap-2 text-[12px] text-ink-muted">{t.deadline ? `Due ${fmtDate(t.deadline)}` : 'No deadline'}
                  <span className="ml-auto flex flex-wrap justify-end gap-1.5"><DeckBadge status={deck?.status} /><Badge tone={t.status === 'proposal' ? 'dark' : 'info'}>{t.status === 'proposal' ? 'Ready for review' : 'Draft'}</Badge></span></div>
                <div className="mt-4 flex gap-2 pt-1">
                  <Link to={`/tenders/${t.id}`} className="btn-primary btn-sm flex-1">Open</Link>
                  {deckUrl ? <Link className="btn-secondary btn-sm" to={deckUrl} title="Opens the deck editor here; PPTX and PDF are exported there"><Presentation size={14} />Open deck</Link>
                    : <button className="btn-secondary btn-sm" disabled title="Available when the deck is generated (Open, then the Proposal tab)"><FileDown size={14} />PPTX</button>}
                </div>
              </Card>
            )
          })}
        </div>
      )}
    </div>
  )
}

export function Quality() {
  // Loaded before in this session: shown at once, refreshed quietly.
  const [result, setResult] = useState<Benchmark | null>(() => peek.benchmark() ?? null)
  const [error, setError] = useState('')
  const load = useCallback((quiet = false) => {
    if (!quiet) setResult(null)
    setError('')
    benchmark().then(setResult).catch(err => setError(errorText(err)))
  }, [])
  useEffect(() => load(peek.benchmark() !== undefined), [load])
  const methods = Object.entries(result?.real_cvs ?? {})
  const final = result?.real_cvs?.['Rules + reranker (final)']
  const failed = final?.rows.filter(r => !r.pass) ?? []
  // The sets behind the numbers, as the benchmark gives them: they are small, so every rate is shown with its counts.
  const sets = [
    result?.meta && `${result.meta.real_cv_tests} CV checks over ${result.meta.documents} CVs`,
    result?.retrieval && `${result.retrieval.positives} retrieval queries`,
    result?.real_tenders && `${result.real_tenders.lines} requirement lines of ${tenderSet(result.real_tenders)}`,
  ].filter(Boolean)
  return (
    <div className="space-y-6">
      <div><h1 className="text-[28px] font-semibold tracking-tight">Quality</h1><p className="mt-1 text-sm text-ink-muted">How well matching works{sets.length ? `, measured on ${sets.slice(0, -1).join(', ')}${sets.length > 1 ? ' and ' : ''}${sets[sets.length - 1]}` : ''}.</p></div>
      {error ? <ErrorNote message={`Could not load the benchmark results from the RAG service: ${error}`} onRetry={() => load()} /> :
        !result ? <Card><Loading text="Loading benchmark results…" /></Card> :
        !result.available ? <Card><Empty icon={FlaskConical} title="Benchmark not available" text="Run the RAG benchmark to publish live evaluation results." /></Card> : <><div className="grid gap-5 md:grid-cols-3">
        {methods.map(([name, r]) => {
          const isFinal = name.includes('final'), v = Math.round((r.passed / r.total) * 100)
          return (
            <Card key={name} className={`p-5 ${isFinal ? '!border-primary ring-2 ring-primary/15' : ''}`}>
              <div className="flex items-center justify-between"><span className="text-sm text-ink-muted">{name.replace(' (final)', '').replace(' (baseline)', '')}</span>{isFinal ? <Badge tone="info">Final system</Badge> : <Badge>Baseline</Badge>}</div>
              <div className="mt-3 text-[30px] font-semibold leading-none">{r.passed}<span className="text-lg text-ink-muted"> / {r.total}</span></div>
              <Bar className="mt-4" value={v} tone="primary" />
            </Card>
          )
        })}
      </div>
      <div className="grid grid-cols-1 gap-5 lg:grid-cols-3">
        <Card className="p-5 lg:col-span-2">
          <CardHeader icon={XCircle} title="Failed checks" tone="bad" hint="Regression checks, not an untouched holdout set. A pass checks status, allowed documents and counts." />
          <div className="-mx-5 overflow-x-auto"><table className="w-full text-sm"><thead><tr><th className="th">Requirement</th><th className="th">Expected</th><th className="th">Got</th></tr></thead>
            <tbody>{failed.map(r => <tr key={r.q}><td className="td font-medium">{r.q}</td><td className="td"><Badge tone="bad">{r.expect}</Badge></td><td className="td"><Badge tone="neutral">{r.got}</Badge></td></tr>)}</tbody></table></div>
        </Card>
        <Card className="p-5">
          <CardHeader icon={FlaskConical} title="Application tests" />
          <div className="flex items-center gap-2 text-[22px] font-semibold"><CheckCircle2 className="text-primary" />{result.tests?.counts?.passed ?? '–'} passed</div>
          <p className="mt-1 text-[13px] text-ink-muted">{result.tests?.summary}</p>
          <p className="mt-4 text-[12px] text-ink-muted">Last benchmark: {result.meta?.finished_at?.slice(0, 16).replace('T', ' ')}</p>
        </Card>
      </div>
      {result.retrieval && <RetrievalCard r={result.retrieval} />}
      {result.real_tenders && <RealTendersCard r={result.real_tenders} />}</>}
    </div>
  )
}

const METRICS = [['ndcg@5', 'nDCG@5'], ['p@3', 'P@3'], ['r@5', 'R@5'], ['mrr', 'MRR'], ['hit@1', 'Hit@1']] as const
const CORPUS: Record<string, string> = { cv: 'CVs', past_project: 'projects', client_portfolio: 'clients', tech_stack: 'stacks', tool: 'tools' }
const score = (v: number | undefined) => (v == null ? '–' : v.toFixed(2))
const ratio = (a?: { correct: number; lines: number }) => (a ? `${a.correct}/${a.lines}` : '–')

function RetrievalCard({ r }: { r: NonNullable<Benchmark['retrieval']> }) {
  const systems = Object.entries(r.systems)
  const final = systems.find(([name]) => name.includes('Final'))?.[1]
  const corpus = Object.entries(r.corpus ?? {}).map(([k, n]) => `${n} ${CORPUS[k] ?? k}`).join(', ')
  return (
    <Card>
      <div className="p-5 pb-0">
        <CardHeader icon={Search} title="Retrieval" hint="nDCG@5: ranking quality of the top 5. P@3: share of the top 3 that is relevant. R@5: share of the relevant documents in the top 5. MRR: 1 / rank of the first relevant one. Hit@1: the first one is relevant." />
        <p className="-mt-2 mb-3 text-[13px] text-ink-muted">{r.positives} labelled queries{r.french_positives ? ` (${r.french_positives} in French)` : ''} and {r.negatives} with no right answer{corpus ? `, over ${corpus}` : ''}.</p>
      </div>
      <div className="overflow-x-auto"><table className="w-full text-sm">
        <thead><tr><th className="th">System</th>{METRICS.map(([, label]) => <th key={label} className="th">{label}</th>)}<th className="th">Median time</th></tr></thead>
        <tbody>{systems.map(([name, s]) => {
          const isFinal = name.includes('Final')
          return <tr key={name} className={isFinal ? 'bg-primary-soft/50' : ''}><td className="td font-medium">{name}{isFinal && <Badge tone="info" className="ml-2">Final system</Badge>}</td>
            {METRICS.map(([k]) => <td key={k} className="td tabular-nums">{score(s[k])}</td>)}<td className="td tabular-nums text-ink-muted">{s.latency_ms_median != null ? `${Math.round(s.latency_ms_median)} ms` : '–'}</td></tr>
        })}</tbody>
      </table></div>
      {final && <p className="px-5 py-3 text-[13px] text-ink-muted">Final system: the documents it keeps as proof have a precision of {score(final.set_precision)} and a recall of {score(final.set_recall)}
        {final.negatives ? `; ${final.negatives.false_positives.length} of the ${final.negatives.total} queries with no right answer still got one${final.negatives.false_positives.length ? ` (${final.negatives.false_positives.join(', ')})` : ''}` : ''}.</p>}
    </Card>
  )
}

const EXPECTED = [['covered', 'Covered'], ['partial', 'Partial'], ['missing', 'Missing']] as const
// The n8n run behind the tender lines sent its real tenders in Company mode and the synthetic demo tenders (the Sampleville
// buyers) in Demo mode: the two are counted apart.
const TENDER_MODE: Record<string, [string, string]> = { company: ['real', 'Real tenders · company data'], demo: ['synthetic demo', 'Synthetic demo tenders · demo data'] }

/** How many tenders of each data mode the lines come from, Company mode first. */
function tendersByMode(r: RealTenders): [string, number][] {
  const seen = new Map<string, Set<string>>()
  for (const x of r.per_line ?? []) if (x.tender_id) seen.set(x.data_mode, (seen.get(x.data_mode) ?? new Set()).add(x.tender_id))
  return [...seen].map(([mode, ids]): [string, number] => [mode, ids.size]).sort(([a], [b]) => Number(b === 'company') - Number(a === 'company'))
}
const tenderSet = (r: RealTenders) => {
  const parts = tendersByMode(r).map(([mode, n]) => `${n} ${TENDER_MODE[mode]?.[0] ?? mode}`)
  return `${r.tenders} tenders from an n8n run${parts.length ? ` (${parts.join(', ')})` : ''}`
}

function RealTendersCard({ r }: { r: RealTenders }) {
  const s = r.summary
  const wrong = (r.per_line ?? []).filter(x => !x.ok)
  return (
    <div className="grid grid-cols-1 gap-5 lg:grid-cols-3">
      <Card className="p-5">
        <CardHeader icon={ListChecks} title="Tender lines" hint="Requirement lines n8n sent in one run, labelled by hand: the status the RAG gives (covered, partial, missing) against the label. Real tenders ran in Company mode, the synthetic demo tenders in Demo mode." />
        <div className="text-[30px] font-semibold leading-none">{s.correct}<span className="text-lg text-ink-muted"> / {s.lines}</span></div>
        <p className="mt-1 text-[13px] text-ink-muted">right status ({Math.round(s.accuracy * 100)}%) on {tenderSet(r)}</p>
        <Bar className="mt-4" value={s.accuracy * 100} />
        <dl className="mt-4 space-y-1.5 text-[13px]">
          {Object.entries(s.by_mode ?? {}).map(([mode, a]) => <div key={mode} className="flex justify-between gap-2"><dt className="text-ink-muted">{TENDER_MODE[mode]?.[1] ?? mode}</dt><dd className="font-medium">{ratio(a)}</dd></div>)}
          {EXPECTED.map(([k, label]) => s.by_expected?.[k] && <div key={k} className="flex justify-between gap-2"><dt className="text-ink-muted">Labelled {label.toLowerCase()}</dt><dd className="font-medium">{ratio(s.by_expected[k])}</dd></div>)}
          {s.over_claims && <div className="flex justify-between gap-2"><dt className="text-ink-muted">Over-claims (more than proved)</dt><dd className="font-medium">{s.over_claims.length}</dd></div>}
          {s.under_claims && <div className="flex justify-between gap-2"><dt className="text-ink-muted">Under-claims</dt><dd className="font-medium">{s.under_claims.length}</dd></div>}
          {s.claimed != null && s.right_proof != null && <div className="flex justify-between gap-2"><dt className="text-ink-muted">Claims with the right proof</dt><dd className="font-medium">{s.right_proof}/{s.claimed}</dd></div>}
        </dl>
      </Card>
      <Card className="p-5 lg:col-span-2">
        <CardHeader icon={XCircle} title="Lines with the wrong status" tone="bad" hint="In red: an over-claim, a status higher than the documents prove." />
        {wrong.length ? (
          <div className="-mx-5 overflow-x-auto"><table className="w-full text-sm"><thead><tr><th className="th">Line</th><th className="th">Data</th><th className="th">Expected</th><th className="th">Got</th></tr></thead>
            <tbody>{wrong.map(x => <tr key={x.id}><td className="td"><div className="font-medium">{x.line}</div><div className="text-[12px] text-ink-muted">{x.id}{x.tender_id ? ` · ${x.tender_id}` : ''} · {x.category}</div></td>
              <td className="td text-ink-muted">{x.data_mode}</td><td className="td"><Badge tone="info">{x.expect}</Badge></td><td className="td"><Badge tone={s.over_claims?.includes(x.id) ? 'bad' : 'neutral'}>{x.got}</Badge></td></tr>)}</tbody></table></div>
        ) : <p className="text-sm text-ink-muted">None.</p>}
      </Card>
    </div>
  )
}

const STUDIO_STATE = {
  checking: ['neutral', 'Checking…'], ready: ['good', 'Connected'], off: ['warn', 'Connected · deck generation not configured'], down: ['bad', 'Unavailable'],
} as const

export function Settings() {
  const [service, setService] = useState<Health | null>(null)
  const [serviceError, setServiceError] = useState('')
  // The proposal studio is optional for the other pages, which hide its errors: its state is shown here.
  const [studio, setStudio] = useState<keyof typeof STUDIO_STATE>('checking')
  // n8n's /healthz sends no CORS header: the no-cors probe tells only whether a server answers at that address.
  const [n8n, setN8n] = useState<boolean | null>(null)
  useEffect(() => {
    health().then(setService).catch(err => setServiceError(err instanceof Error ? err.message : 'Unavailable'))
    studioTenders().then(inbox => setStudio(inbox.generationEnabled ? 'ready' : 'off')).catch(() => setStudio('down'))
    n8nAnswers().then(setN8n)
  }, [])
  const [studioTone, studioLabel] = STUDIO_STATE[studio]
  const rows = [
    { icon: Server, label: 'RAG service', value: 'http://127.0.0.1:8001', badge: <Badge tone={service ? 'good' : serviceError ? 'bad' : 'neutral'}>{service ? 'Connected' : serviceError ? 'Unavailable' : 'Checking…'}</Badge> },
    { icon: Presentation, label: 'Proposal studio', value: STUDIO, badge: <Badge tone={studioTone}>{studioLabel}</Badge>,
      action: <Link to="/templates" className="btn-secondary btn-sm"><LayoutTemplate size={14} />Deck templates</Link> },
    { icon: Sparkles, label: 'AI agents (n8n)', value: `${N8N} · Refine with AI on the deck page`,
      tip: 'Reachable means a server answers at this address. Whether the "RFP - Refine Slide" workflow is active shows only when a slide is refined.',
      badge: <Badge tone={n8n == null ? 'neutral' : n8n ? 'good' : 'bad'}>{n8n == null ? 'Checking…' : n8n ? 'Reachable' : 'Unavailable'}</Badge> },
    { icon: Cpu, label: 'Embedding model', value: service?.model ?? 'Unavailable' },
    { icon: Gauge, label: 'Reranker', value: service?.reranker ?? 'Unavailable' },
    { icon: Database, label: 'Data mode', value: 'Company by default; Demo is available per analysis', badge: <Badge>Live API</Badge> },
  ]
  return (
    <div className="space-y-6">
      <div><h1 className="text-[28px] font-semibold tracking-tight">Settings</h1><p className="mt-1 text-sm text-ink-muted">Service connection and data sources.</p></div>
      <Card className="divide-y divide-line">
        {rows.map(({ icon: Icon, label, value, badge, action, tip }) => (
          <div key={label} className="flex flex-wrap items-center gap-4 px-5 py-4">
            <span className="grid h-9 w-9 place-items-center rounded-[10px] bg-primary-soft text-primary"><Icon size={18} /></span>
            <div className="min-w-0 flex-1"><div className="flex items-center gap-1 text-sm font-medium">{label}{tip && <Tip text={tip} />}</div><div className="truncate text-[13px] text-ink-muted">{value}</div></div>{action}{badge}
          </div>
        ))}
      </Card>
      {serviceError && <p className="rounded-ctl bg-bad-soft px-3 py-2 text-sm text-bad">{serviceError}</p>}
    </div>
  )
}
